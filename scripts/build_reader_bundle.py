#!/usr/bin/env python3
"""Build or check the classic-script bundle used by Bookcast chapter readers."""

import argparse
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
READER = ROOT / "public" / "reader"
OUTPUT = READER / "reader-bundle.js"
TEMPLATES = (
    ROOT / ".agents/skills/bilingual-audio-reader/scripts/reader.template.html",
    ROOT / ".agents/skills/trilingual-audio-reader/scripts/reader.template.html",
    ROOT / "src/lalka-2/reader.template.html",
)
REFERENCE = re.compile(r'(?<=\.\./reader/reader-bundle\.js\?v=)[0-9a-f]{16}(?=")')
SOURCES = (
    "audio-loader.js",
    "footnotes.js",
    "timing.js",
    "storage.js",
    "state.js",
    "render.js",
    "playback.js",
    "controls-input.js",
    "translations.js",
    "controls-common.js",
    "keyboard.js",
    "boot.js",
)


def build():
    pieces = ["// Generated by scripts/build_reader_bundle.py. Do not edit.\n"]
    for name in SOURCES:
        source = (READER / name).read_text(encoding="utf-8")
        pieces.append(f"\n// --- {name} ---\n{source.rstrip()}\n;\n")
    return "".join(pieces)


def reader_pages():
    pages = sorted(p for p in (ROOT / "public").glob("*/chapter-*.html")
                   if not p.name.endswith((".vocab.html", ".timestamp-helper.html")))
    return (*TEMPLATES, *pages)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the bundle is missing or stale")
    args = parser.parse_args()
    content = build()
    version = hashlib.sha256(content.encode("utf-8")).hexdigest()[:16]
    references = {}
    for path in reader_pages():
        text = path.read_text(encoding="utf-8")
        matches = REFERENCE.findall(text)
        if len(matches) != 1:
            raise SystemExit(f"Expected one versioned bundle reference in {path.relative_to(ROOT)}")
        references[path] = (text, matches[0])
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("Reader bundle is missing or stale; run scripts/build_reader_bundle.py")
        stale = [str(path.relative_to(ROOT)) for path, (_, value) in references.items() if value != version]
        if stale:
            raise SystemExit(f"Reader bundle references are stale: {', '.join(stale)}")
        print(f"Reader bundle is current (version {version}).")
    else:
        OUTPUT.write_text(content, encoding="utf-8")
        for path, (text, old_version) in references.items():
            if old_version != version:
                path.write_text(REFERENCE.sub(version, text, count=1), encoding="utf-8")
        print(f"Wrote {OUTPUT.relative_to(ROOT)} (version {version}).")


if __name__ == "__main__":
    main()
