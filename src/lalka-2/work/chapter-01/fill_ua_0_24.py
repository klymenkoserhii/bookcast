i = 0
start_unit = None
for ln in range(len(lines)):
    m = re.match(r'^\*\*PL:\*\*\s*(.*)$', lines[ln])
    if m:
        if start_unit is None:
            start_unit = i
        i += 1
        continue
    m2 = re.match(r'^\*\*UA:\*\*\s*$', lines[ln])
    if m2 and start_unit is not None:
        unit_idx = start_unit
        if unit_idx in translations:
            lines[ln] = '**UA:** ' + translations[unit_idx]
        start_unit = None

open(path, 'w', encoding='utf-8').write('\n'.join(lines))
